    g.tri((c.x - s, c.y + s * 0.65), (c.x - s * 0.35, c.y - s * 0.85), (c.x + s, c.y + s * 0.65), [0.44, 0.36, 0.28, 0.7]);
    // 坑道入口（木枠と暗がり）
    let mw = s * 0.36;
